// 第 4 章 数据库物理设计
const { h1, h2, h3, body, bodies, lead, note, tbl, tblTitle, codeBlock } = require("./helpers");

function ch4() {
  const out = [];
  out.push(h1("4  数据库物理设计"));
  out.push(body("第一版实现落在单个 PostgreSQL 实例：记录、事务、JSONB 载荷副本与必要索引全部入库，正文与附件放对象存储，初期全文检索直接使用数据库 tsvector。研究设计报告第 12.1 节的存储对象清单在本章落为具体表结构；关系数据库、图数据库与向量索引是后续阶段的性能选择，不是语义依赖。"));

  out.push(h2("4.1  表清单与一致性要求"));
  out.push(tblTitle("表清单"));
  out.push(tbl(
    ["表", "职责", "一致性要求", "对应模块"],
    [
      ["workspace / branch", "工作空间、分支与两个纪元的当前值", "强一致；epoch 推进与失效事务同库", "M1"],
      ["commit", "提交序列（历史日志 L）", "与关键状态变更同事务；序号无空洞", "M1"],
      ["record", "不可变记录（记录集合 R）", "插入后禁 UPDATE/DELETE（触发器强制）", "M1"],
      ["record_ref", "类型化正反向引用边", "与 record 同事务写入；失效索引读此表", "M1/M3"],
      ["object_heads", "逻辑对象当前版本", "强一致；用于准入与读取", "M3"],
      ["task_state", "任务当前工作状态", "强一致", "M3"],
      ["effect_state", "意图效果状态", "强一致；与 outbox、预留同事务", "M2"],
      ["grant / grant_usage", "授权与按意图的次数占用", "强一致；原子检查", "M4"],
      ["budget_ledger / reservation", "预算账本与资源预留", "强一致；可串行化事务内原子预留", "M1/M2"],
      ["effect_outbox / attempt / receipt_view", "待发送动作、尝试与回执投影", "与准备动作同事务写入 outbox", "M2"],
      ["invalidation_queue / index_watermark", "失效队列与异步索引水位", "队列强一致入队；水位由工作者推进", "M3/M6"],
      ["blob_object / tombstone", "对象存储登记与删除墓碑", "墓碑先行持久化", "M4/S"],
    ],
    [24, 32, 28, 16],
    { fontSize: 19 }
  ));

  out.push(h2("4.2  核心表 DDL"));
  out.push(lead("下列 DDL 为第一版权威定义，约束即不变量的第一道实现（映射关系见 8.5 节）。"));

  out.push(...codeBlock([
    "-- 提交与记录（历史日志 L 与记录集合 R）",
    "CREATE TABLE commit (",
    "  commit_id        uuid PRIMARY KEY,",
    "  workspace_id     uuid NOT NULL,",
    "  branch_id        uuid NOT NULL DEFAULT 'main',",
    "  sequence         bigint NOT NULL,",
    "  previous_commit_id uuid NOT NULL,",
    "  reducer_version  int  NOT NULL,",
    "  record_ids       uuid[] NOT NULL,",
    "  request_id       text NOT NULL,",
    "  request_digest   text NOT NULL,",
    "  committed_at     timestamptz NOT NULL,",
    "  UNIQUE (workspace_id, branch_id, sequence),",
    "  UNIQUE (workspace_id, request_id)          -- I3：幂等键唯一",
    ");",
    "",
    "CREATE TABLE record (",
    "  record_id     uuid PRIMARY KEY,",
    "  object_id     uuid NOT NULL,",
    "  workspace_id  uuid NOT NULL,",
    "  branch_id     uuid NOT NULL DEFAULT 'main',",
    "  kind          text NOT NULL,",
    "  schema_version int NOT NULL CHECK (schema_version >= 1),",
    "  authenticated_writer jsonb NOT NULL,",
    "  asserted_source jsonb,",
    "  recorded_at   timestamptz NOT NULL,",
    "  payload_digest text NOT NULL,",
    "  payload_ref   jsonb NOT NULL,",
    "  payload       jsonb NOT NULL,   -- 规范化副本，仅供校验与索引",
    "  policy_domain text NOT NULL,",
    "  commit_id     uuid NOT NULL REFERENCES commit(commit_id),",
    "  sequence      bigint NOT NULL   -- 冗余分支序号，供 as_of 截断",
    ");",
    "-- 不可变性由触发器强制：禁止 UPDATE / DELETE（回放与测试依赖）",
    "CREATE TRIGGER record_immutable BEFORE UPDATE OR DELETE ON record",
    "  FOR EACH ROW EXECUTE FUNCTION reject_mutation();",
    "CREATE INDEX ON record (workspace_id, branch_id, sequence);",
    "CREATE INDEX ON record (object_id);",
    "CREATE INDEX ON record (kind);",
  ], "commit 与 record 表"));

  out.push(...codeBlock([
    "-- 类型化引用边（正反向查询共用一张表）",
    "CREATE TABLE record_ref (",
    "  src_record_id uuid NOT NULL REFERENCES record(record_id),",
    "  ref_role      text NOT NULL,   -- 3.13 节注册表",
    "  ref_layer     text NOT NULL CHECK (ref_layer IN ('DERIVATION','SEMANTIC','CONTROL')),",
    "  dst_record_id uuid NOT NULL REFERENCES record(record_id),",
    "  dst_object_id uuid NOT NULL,",
    "  note          text,",
    "  PRIMARY KEY (src_record_id, ref_role, dst_record_id)",
    ");",
    "CREATE INDEX ON record_ref (dst_record_id);          -- 反向依赖：失效传播入口",
    "CREATE INDEX ON record_ref (dst_record_id, ref_layer);",
    "",
    "-- 当前版本与任务状态（投影 V 的强一致部分）",
    "CREATE TABLE object_heads (",
    "  workspace_id uuid NOT NULL,",
    "  object_id    uuid NOT NULL,",
    "  head_record_id uuid NOT NULL REFERENCES record(record_id),",
    "  head_sequence bigint NOT NULL,",
    "  updated_at   timestamptz NOT NULL,",
    "  PRIMARY KEY (workspace_id, object_id)",
    ");",
    "",
    "CREATE TABLE task_state (",
    "  workspace_id uuid NOT NULL,",
    "  task_object_id uuid NOT NULL,",
    "  status       text NOT NULL CHECK (status IN",
    "    ('DRAFT','ACTIVE','PENDING_REEVALUATION','COMPLETED','CANCELLED')),",
    "  current_revision uuid NOT NULL REFERENCES record(record_id),",
    "  acceptance_status jsonb NOT NULL,  -- 各验收谓词的当前判定",
    "  reevaluation_reason text,",
    "  PRIMARY KEY (workspace_id, task_object_id)",
    ");",
  ], "record_ref 与投影表"));

  out.push(...codeBlock([
    "-- 授权与使用账目",
    "CREATE TABLE grant_record (",
    "  grant_id     uuid PRIMARY KEY,",
    "  issuer       jsonb NOT NULL,",
    "  grantee      jsonb NOT NULL,",
    "  parent_grant_id uuid REFERENCES grant_record(grant_id),",
    "  operation_digest text NOT NULL,",
    "  scope        jsonb NOT NULL,",
    "  purpose      text NOT NULL,",
    "  expiry       timestamptz NOT NULL,",
    "  revocation_handle uuid NOT NULL,",
    "  use_limit    int NOT NULL CHECK (use_limit >= 1),",
    "  uses_consumed int NOT NULL DEFAULT 0,",
    "  allowed_destinations jsonb NOT NULL,",
    "  policy_version int NOT NULL,",
    "  status       text NOT NULL DEFAULT 'active'",
    ");",
    "CREATE TABLE grant_usage (",
    "  grant_id  uuid NOT NULL REFERENCES grant_record(grant_id),",
    "  intent_id uuid NOT NULL,",
    "  taken_at  timestamptz NOT NULL,",
    "  PRIMARY KEY (grant_id, intent_id)   -- 同一意图重试不重复计数",
    ");",
    "",
    "-- 预算账本与资源预留（I5：预留加已确认消耗不超额度）",
    "CREATE TABLE budget_ledger (",
    "  resource_key text PRIMARY KEY,      -- 如 ws:compute.gpu.a100",
    "  limit_amount numeric NOT NULL CHECK (limit_amount >= 0),",
    "  reserved_amount numeric NOT NULL DEFAULT 0,",
    "  committed_amount numeric NOT NULL DEFAULT 0,",
    "  CHECK (reserved_amount + committed_amount <= limit_amount)",
    ");",
    "CREATE TABLE reservation (",
    "  reservation_id uuid PRIMARY KEY,",
    "  intent_id      uuid NOT NULL,",
    "  resource_key   text NOT NULL REFERENCES budget_ledger(resource_key),",
    "  amount         numeric NOT NULL CHECK (amount > 0),",
    "  state          text NOT NULL CHECK (state IN",
    "    ('reserved','uncertain','committed','released')),",
    "  created_at     timestamptz NOT NULL,",
    "  settled_at     timestamptz",
    ");",
    "CREATE INDEX ON reservation (intent_id);",
  ], "授权、预算与预留表"));

  out.push(...codeBlock([
    "-- 效果状态、outbox 与尝试",
    "CREATE TABLE effect_state (",
    "  workspace_id uuid NOT NULL,",
    "  intent_id    uuid NOT NULL,",
    "  state        text NOT NULL CHECK (state IN ('PROPOSED','PREPARED','IN_FLIGHT',",
    "    'OUTCOME_UNKNOWN','CONFIRMED_SUCCEEDED','CONFIRMED_NOT_APPLIED',",
    "    'CANCELLED_BEFORE_DISPATCH','PARTIAL')),",
    "  unresolved_reason text,",
    "  updated_epoch bigint NOT NULL,",
    "  PRIMARY KEY (workspace_id, intent_id)",
    ");",
    "",
    "CREATE TABLE effect_outbox (",
    "  outbox_id   uuid PRIMARY KEY,",
    "  intent_id   uuid NOT NULL,",
    "  state       text NOT NULL DEFAULT 'PENDING' CHECK (state IN",
    "    ('PENDING','CLAIMED','DONE','ABANDONED')),",
    "  claim_token uuid,",
    "  claim_expires_at timestamptz,",
    "  attempts_count int NOT NULL DEFAULT 0,",
    "  next_retry_at timestamptz NOT NULL DEFAULT now(),",
    "  UNIQUE (intent_id)",
    ");",
    "",
    "CREATE TABLE attempt (",
    "  attempt_id  uuid PRIMARY KEY,",
    "  intent_id   uuid NOT NULL,",
    "  gateway_principal jsonb NOT NULL,",
    "  started_at  timestamptz NOT NULL,",
    "  dispatch_digest text NOT NULL,",
    "  idempotency_key_state jsonb,",
    "  external_job_id text,",
    "  attempt_status text NOT NULL CHECK (attempt_status IN",
    "    ('STARTED','RESPONSE_PERSISTED','NO_RESPONSE'))",
    ");",
    "CREATE INDEX ON attempt (intent_id);",
  ], "效果执行表"));

  out.push(...codeBlock([
    "-- 失效传播、水位与删除域",
    "CREATE TABLE workspace_epoch (",
    "  workspace_id   uuid PRIMARY KEY,",
    "  validation_epoch bigint NOT NULL DEFAULT 1,",
    "  policy_epoch     bigint NOT NULL DEFAULT 1,",
    "  head_sequence    bigint NOT NULL DEFAULT 0",
    ");",
    "",
    "CREATE TABLE invalidation_queue (",
    "  item_id     bigserial PRIMARY KEY,",
    "  workspace_id uuid NOT NULL,",
    "  epoch       bigint NOT NULL,        -- 触发本次失效的验证纪元",
    "  root_record_id uuid NOT NULL,       -- 失效根（被撤回/更正/删除的记录）",
    "  status      text NOT NULL DEFAULT 'PENDING' CHECK (status IN",
    "    ('PENDING','PROCESSING','DONE')),",
    "  created_at  timestamptz NOT NULL",
    ");",
    "",
    "CREATE TABLE invalidation_mark (",
    "  workspace_id uuid NOT NULL,",
    "  record_id    uuid NOT NULL,         -- 受影响的下游记录",
    "  path_role    text NOT NULL,         -- 命中的依赖路径类型",
    "  via_record_id uuid NOT NULL,        -- 传播路径上的直接依赖者",
    "  epoch        bigint NOT NULL,",
    "  PRIMARY KEY (workspace_id, record_id, via_record_id)",
    ");",
    "",
    "CREATE TABLE index_watermark (",
    "  index_name      text PRIMARY KEY,",
    "  applied_sequence bigint NOT NULL,",
    "  validation_epoch bigint NOT NULL,",
    "  updated_at      timestamptz NOT NULL",
    ");",
    "",
    "CREATE TABLE tombstone (",
    "  object_id    uuid NOT NULL,",
    "  record_id    uuid,                  -- 记录级或对象级删除",
    "  payload_digest text,                -- 载荷级删除",
    "  policy_domain text NOT NULL,",
    "  purged_at    timestamptz NOT NULL,",
    "  policy_epoch bigint NOT NULL,       -- 先于清理持久化（第 7.8 节）",
    "  PRIMARY KEY (object_id, record_id, payload_digest)",
    ");",
    "",
    "CREATE TABLE blob_object (",
    "  blob_id     uuid PRIMARY KEY,",
    "  digest      text NOT NULL,",
    "  media_type  text NOT NULL,",
    "  size_bytes  bigint NOT NULL,",
    "  storage_uri text NOT NULL,",
    "  deletion_state text NOT NULL DEFAULT 'live' CHECK (deletion_state IN",
    "    ('live','pending_purge','purged')),",
    "  data_labels jsonb NOT NULL DEFAULT '[]'",
    ");",
  ], "失效、水位与删除域表"));

  out.push(h2("4.3  索引设计"));
  out.push(body("除 DDL 中内联的索引外，读取路径补充以下索引：record (kind, recorded_at) 支持按类型的近期扫描；record (payload->>'target_claim_id') 支持主张到论证的反查（JSONB GIN 索引按查询模式在阶段 A 压测后决定取舍）；record_ref (src_record_id, ref_layer) 支持正向遍历；attempt (started_at) 支持超时巡检；effect_outbox (state, next_retry_at) 部分索引 WHERE state IN ('PENDING','CLAIMED') 支撑网关领取扫描。所有索引的选择依据与复杂度注明条件见第 11 章，不得以加索引替代闸门逻辑。"));

  out.push(h2("4.4  约束与不变量的第一道防线"));
  out.push(body("数据库层实现的不变量：I3 由 commit 表两个唯一约束实现，request_id 重复但 request_digest 不同时，写入服务在捕获唯一冲突后比对摘要并拒绝（E202）；I5 由 budget_ledger 的 CHECK 约束加可串行化事务内的条件更新实现，CHECK 只是最后防线，正常路径是先 SELECT FOR UPDATE 后判断余额；I1 由 record_immutable 触发器实现；I4 由 object_heads 的条件更新（WHERE head_sequence < 新序号）实现。I2、I6 至 I10 无法用声明式约束表达，由写入服务与网关在事务内执行程序化检查，检查点见第 5、7 章。"));

  out.push(h2("4.5  增长控制与归档"));
  out.push(body("第一版不分区。阶段 E 提供两个预留：record 与 commit 按月分区的方案（以 sequence 范围切分，配合回放按序号截断）；历史压缩方案（将已无活跃依赖且超过审计保留期的旧提交载荷迁移冷存储，仅保留摘要与拓扑）。压缩只能改变存储形式，不得丢弃仍需审计的版本、未完成动作或删除域尚未处理完成的记录。对象存储按 blob 的 deletion_state 生命周期规则清理，清理以墓碑存在为前提。"));
  return out;
}

